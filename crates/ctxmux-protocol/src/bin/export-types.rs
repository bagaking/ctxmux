use std::{
    env,
    error::Error,
    fs,
    path::{Path, PathBuf},
    process::ExitCode,
};

use ctxmux_protocol::{
    AttachedSnapshot, ClientFrame, MAX_CREATE_OPERATION_KEY_BYTES, MAX_FRAME_BYTES,
    PROTOCOL_VERSION, ServerFrame,
};
use ts_rs::{Config, TS};

fn main() -> ExitCode {
    let Some(output) = env::args_os().nth(1).map(PathBuf::from) else {
        eprintln!("usage: export-types <output-directory>");
        return ExitCode::from(2);
    };
    if let Err(error) = export(&output) {
        eprintln!("failed to export TypeScript protocol bindings: {error}");
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

fn export(output: &Path) -> Result<(), Box<dyn Error>> {
    fs::create_dir_all(output)?;
    let config = Config::default()
        .with_out_dir(output)
        .with_import_extension(Some("js"))
        .with_large_int("number");
    ClientFrame::export_all(&config)?;
    ServerFrame::export_all(&config)?;
    AttachedSnapshot::export_all(&config)?;
    fs::write(
        output.join("constants.ts"),
        format!(
            concat!(
                "// Generated by ctxmux-protocol. Do not edit manually.\n",
                "export const PROTOCOL_VERSION = {} as const;\n",
                "export const MAX_FRAME_BYTES = {} as const;\n",
                "export const MAX_CREATE_OPERATION_KEY_BYTES = {} as const;\n"
            ),
            PROTOCOL_VERSION, MAX_FRAME_BYTES, MAX_CREATE_OPERATION_KEY_BYTES,
        ),
    )?;
    Ok(())
}
